export function buildRouteYoutubeQuery(route: GlobalRouteNode, mode: FeedMode): string {
  if (mode === 'vibe') {
    return `대한항공 ${route.destCity} 여행 공항 라운지 브이로그`
  }
  return `대한항공 ${route.destCity} ${route.aircraftName} 기내식 탑승기`
}

export function filterRouteVideos(routeId: string, mode: FeedMode): YoutubeReviewItem[] {
  const ranked = ROUTE_FALLBACK_VIDEOS.map((entry) => {
    let score = 0
    if (entry.routeIds.includes(routeId)) score += 6
    if (entry.video.category === mode) score += 4
    return { video: entry.video, score }
  })
    .filter((item) => item.video.category === mode)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.video)

  return ranked.slice(0, 4)
}
